-- Week 9: the Prompt Chain Tool (its own app, same Journey database).
-- Adds "custom" chains whose steps run one after another (each step's output feeds the next),
-- lets superadmins create/update/delete chains and steps and reorder steps,
-- and stores the media custom chains generate.
-- Journey's own chains (trip / profile) keep working exactly as before.

-- 1) New kinds -------------------------------------------------------------------
alter table public.prompt_chains drop constraint if exists prompt_chains_kind_check;
alter table public.prompt_chains add constraint prompt_chains_kind_check
  check (kind in ('trip', 'profile', 'custom'));

alter table public.prompt_chain_steps drop constraint if exists prompt_chain_steps_role_check;
alter table public.prompt_chain_steps add constraint prompt_chain_steps_role_check
  check (role in ('locate', 'write', 'parse', 'text'));                 -- text = a free-form step in a custom chain
alter table public.prompt_chain_steps add column if not exists uses_image boolean not null default false;

alter table public.generation_requests drop constraint if exists generation_requests_kind_check;
alter table public.generation_requests add constraint generation_requests_kind_check
  check (kind in ('trip', 'lucky', 'profile', 'admin', 'tool'));        -- tool = a run in the Prompt Chain Tool

alter table public.prompt_chains add column if not exists updated_at timestamptz not null default now();

-- 2) Superadmins can now change chains and steps (reading stays open to logged-in users, as before) --
drop policy if exists "prompt_chains: admin write" on public.prompt_chains;
create policy "prompt_chains: admin write" on public.prompt_chains
  for all to authenticated using (public.is_superadmin()) with check (public.is_superadmin());
drop policy if exists "prompt_chain_steps: admin write" on public.prompt_chain_steps;
create policy "prompt_chain_steps: admin write" on public.prompt_chain_steps
  for all to authenticated using (public.is_superadmin()) with check (public.is_superadmin());
-- a new trip chain needs its row in the mix
drop policy if exists "prompt_chain_mix: admin insert" on public.prompt_chain_mix;
create policy "prompt_chain_mix: admin insert" on public.prompt_chain_mix
  for insert to authenticated with check (public.is_superadmin());

-- 3) Reorder: put a chain's steps in the given order (1, 2, 3 …) in one go.
-- step_order is unique per chain, so steps are parked at negative numbers first.
create or replace function public.reorder_prompt_chain_steps(p_chain_id bigint, p_step_ids bigint[])
returns void language plpgsql security invoker set search_path = public as $$
declare n int;
begin
  if not public.is_superadmin() then raise exception 'admins only'; end if;
  select count(*) into n from public.prompt_chain_steps where chain_id = p_chain_id;
  if n <> coalesce(array_length(p_step_ids, 1), 0)
     or exists (select 1 from unnest(p_step_ids) s where s not in (select id from public.prompt_chain_steps where chain_id = p_chain_id)) then
    raise exception 'the new order must list every step of this chain exactly once';
  end if;
  update public.prompt_chain_steps set step_order = -step_order where chain_id = p_chain_id;
  update public.prompt_chain_steps s set step_order = o.pos
    from unnest(p_step_ids) with ordinality as o(id, pos)
    where s.id = o.id and s.chain_id = p_chain_id;
  update public.prompt_chains set updated_at = now() where id = p_chain_id;
end $$;
revoke execute on function public.reorder_prompt_chain_steps(bigint, bigint[]) from public, anon;
grant execute on function public.reorder_prompt_chain_steps(bigint, bigint[]) to authenticated;

-- 4) Media generated by custom chains ---------------------------------------------
create table if not exists public.generated_media (
  id bigint generated always as identity primary key,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.profiles(id) on delete set null,
  chain_id bigint not null references public.prompt_chains(id) on delete cascade,
  request_id uuid references public.generation_requests(id) on delete set null,
  input_text text,
  input_image_url text,
  steps jsonb not null default '[]',      -- [{step_id, name, output}] — what each step produced
  output text not null                    -- the last step's output: the media itself
);
create index if not exists generated_media_chain on public.generated_media (chain_id, created_at desc);
alter table public.generated_media enable row level security;
drop policy if exists "generated_media: admin all" on public.generated_media;
create policy "generated_media: admin all" on public.generated_media
  for all to authenticated using (public.is_superadmin()) with check (public.is_superadmin());

-- 5) A starter custom chain, like the assignment's image → description → funny → captions --------
insert into public.prompt_chains (slug, name, kind, description)
values ('trip-photo-captions', 'Trip photo → captions', 'custom',
        'Give it a photo from a trip: it describes the scene, finds the funny part, then writes five captions for a Journey trip card.')
on conflict (slug) do nothing;

insert into public.prompt_chain_steps (chain_id, step_order, role, name, model_id, temperature, thinking_level, uses_image, instructions)
select c.id, s.step_order, 'text', s.name, (select id from public.llm_models where model_key = s.model_key), s.temperature, 'low', s.uses_image, s.instructions
from public.prompt_chains c
join (values
  (1, 'Describe the photo', 'gemini-flash-latest', 0.3, true,
   'Describe this photo from a New York City trip in 3–4 plain sentences: where it probably is, what is in it, the light and the mood. {input}'),
  (2, 'Find the funny part', 'gemini-flash-latest', 0.9, false,
   'Here is a description of a trip photo:
{previous}

What is the funniest true-to-NYC observation a Columbia student new to the city would make about it? Give 3 short ideas.'),
  (3, 'Write five captions', 'gemini-flash-latest', 1.0, false,
   'Using these ideas:
{previous}

Write five short, funny captions for a Journey trip card. Number them 1–5. At most 12 words each. No emojis, no hashtags.')
) as s(step_order, name, model_key, temperature, uses_image, instructions) on true
where c.slug = 'trip-photo-captions'
on conflict (chain_id, step_order) do nothing;
